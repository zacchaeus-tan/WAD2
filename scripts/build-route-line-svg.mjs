// Builds supabase/migrations/0013_route_line_svg_data.sql: one small SVG path per route
// (routes.line_svg) for the browse tiles, made with the same geometryToPath() the app uses.
// Run it again after importing or changing route lines:
//   node scripts/build-route-line-svg.mjs
// Reads the routes with the public key in .env; routes are publicly readable.

import { readFileSync, writeFileSync } from 'node:fs'
import { createClient } from '@supabase/supabase-js'
import { geometryToPath } from '../src/lib/routeLine.js'

const OUTPUT = new URL('../supabase/migrations/0013_route_line_svg_data.sql', import.meta.url)

// KEY=value lines from .env, ignoring blanks and comments
function readEnv() {
  const env = {}
  for (const line of readFileSync(new URL('../.env', import.meta.url), 'utf8').split('\n')) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/)
    if (match) {
      env[match[1]] = match[2].replace(/^["']|["']$/g, '')
    }
  }
  return env
}

function sqlText(value) {
  return value == null ? 'null' : `'${value.replaceAll("'", "''")}'`
}

const env = readEnv()
const supabase = createClient(env.VITE_SUPABASE_URL, env.VITE_SUPABASE_PUBLISHABLE_KEY)

const { data: routes, error } = await supabase
  .from('routes')
  .select('name, osm_id, geometry')
  .not('osm_id', 'is', null)
  .order('osm_id')
if (error) {
  throw error
}

const statements = routes.map(
  (route) => `-- ${route.name}
update public.routes
   set line_svg = ${sqlText(geometryToPath(route.geometry))}
 where osm_id = ${sqlText(route.osm_id)};`,
)

writeFileSync(
  OUTPUT,
  `-- Generated by scripts/build-route-line-svg.mjs — do not edit by hand.\n\n${statements.join('\n\n')}\n`,
)
console.log(`Wrote ${routes.length} route lines to ${OUTPUT.pathname}`)
