// Builds supabase/migrations/0010_route_geometry_data.sql from the raw
// OpenStreetMap exports in the public route-geojson storage bucket.
//
//   node --env-file=.env.local scripts/build-route-geometry.mjs
//
// To link another route, add its name and OSM id to MATCHES, re-run, then
// run the generated SQL in the Supabase SQL editor.
import { writeFileSync } from 'node:fs'

const BUCKET = 'route-geojson'
const FILES = [
  'indonesia-routes.geojson',
  'malaysia-routes.geojson',
  'phillipines-routes.geojson',
  'singapore-routes.geojson',
  'thailand-routes.geojson',
  'vietnam-routes.geojson',
]
const OUTPUT = 'supabase/migrations/0010_route_geometry_data.sql'

// routes.name -> OSM "@id" of the trail in the exports.
const MATCHES = {
  'Cameron Highlands Trail 5': 'relation/11758338', // Gunung Berembun via Trail 5
  'Mount Rinjani via Sajang': 'relation/17259217', // Mount Rinjani (Sembalun BC)
  // Approximate: closest trail in the exports, not the exact route.
  'Mount Kinabalu Trail': 'relation/3112158', // Mt. Kinabalu Climbathon Summit Race
  'Gunung Lambak via Gunung Lambak Trailhead': 'relation/19912102', // Lambak Butterfly
}

const baseUrl = process.env.VITE_SUPABASE_URL
if (!baseUrl) throw new Error('VITE_SUPABASE_URL is not set — run with --env-file=.env.local')

const features = new Map()
for (const file of FILES) {
  const response = await fetch(`${baseUrl}/storage/v1/object/public/${BUCKET}/${file}`)
  if (!response.ok) throw new Error(`Could not load ${file}: ${response.status}`)
  const collection = await response.json()
  for (const feature of collection.features) features.set(feature.properties?.['@id'], feature)
}

const quote = (value) => `'${String(value).replace(/'/g, "''")}'`

const statements = Object.entries(MATCHES).map(([name, osmId]) => {
  const feature = features.get(osmId)
  if (!feature) throw new Error(`${osmId} (${name}) is not in the exports`)
  return [
    `-- ${name} <- ${feature.properties.name || 'unnamed'}`,
    'update public.routes',
    `   set osm_id = ${quote(osmId)},`,
    `       geometry = ${quote(JSON.stringify(feature.geometry))}::jsonb`,
    ` where name = ${quote(name)};`,
  ].join('\n')
})

writeFileSync(
  OUTPUT,
  `-- Generated by scripts/build-route-geometry.mjs — do not edit by hand.\n\n${statements.join('\n\n')}\n`,
)
console.log(`Wrote ${statements.length} routes to ${OUTPUT}`)
